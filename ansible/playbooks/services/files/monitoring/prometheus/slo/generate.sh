#!/usr/bin/env bash
# Regenerates ../alerts/slo.yml from slos.sloth.yml with Sloth, then validates it with promtool.
# Needs Docker. Commit both files.
set -euo pipefail
cd "$(dirname "$0")"
SLOTH_IMAGE="ghcr.io/slok/sloth:v0.11.0"
PROM_IMAGE="prom/prometheus:v2.48.1"
{
  echo "# GENERATED by Sloth from ../slo/slos.sloth.yml. Do not edit by hand: change the spec and run ../slo/generate.sh."
  docker run --rm -v "$PWD:/w" "$SLOTH_IMAGE" generate -i /w/slos.sloth.yml
} > ../alerts/slo.yml.tmp
mv ../alerts/slo.yml.tmp ../alerts/slo.yml
docker run --rm --entrypoint promtool -v "$PWD/..:/w" "$PROM_IMAGE" check rules /w/alerts/slo.yml
